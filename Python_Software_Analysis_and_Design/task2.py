# Step 1: Create variables first_number and second_number
first_number = 5   
second_number = 10  

# Print the values of both variables
print("First Number:", first_number)    
print("Second Number:", second_number) 

# Step 2: Perform mathematical operations using the variables
# Add the two numbers
print("Addition (first_number + second_number):", first_number + second_number)  
# Subtract the first number from the second number
print("Subtraction (second_number - first_number):", second_number - first_number) 
# Multiply the two numbers
print("Multiplication (first_number * second_number):", first_number * second_number)  
# Divide the second number by the first number
print("Division (second_number / first_number):", second_number / first_number) 

# Step 3: Store the results of the operations in variables
# Perform each operation and store the result in new variables
addition = first_number + second_number   
subtraction = second_number - first_number  
multiplication = first_number * second_number  
division = second_number / first_number   

# Print the results stored in the new variables
print("Stored Addition:", addition)         
print("Stored Subtraction:", subtraction)   
print("Stored Multiplication:", multiplication)  
print("Stored Division:", division)         
